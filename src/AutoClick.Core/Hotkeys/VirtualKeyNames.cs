/// <summary>
/// Key names used in hotkey strings, mapped to Win32 virtual-key codes.
/// </summary>
/// <remarks>
/// The table mirrors WPF's <c>System.Windows.Input.Key</c> names and
/// <c>KeyInterop.VirtualKeyFromKey</c>, because v1 stored hotkeys as <c>Key.ToString()</c>.
/// Keeping it here avoids a WPF dependency in Core; a test in AutoClick.Win32.Tests checks
