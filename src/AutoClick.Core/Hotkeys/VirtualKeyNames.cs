public static class VirtualKeyNames
{
    /// <summary>All (name, virtual key) pairs, including WPF aliases such as Enter/Return.</summary>
    public static IEnumerable<(string Name, int Vk)> All => Names;

    public static bool TryGetVirtualKey(string name, out int virtualKey) =>
        Maps.ByName.TryGetValue(name, out virtualKey);

    /// <summary>Name WPF would write for <paramref name="virtualKey"/>, or null when unknown.</summary>
    public static string? GetName(int virtualKey) =>
        Maps.ByCode.TryGetValue(virtualKey, out var name) ? name : null;

    /// <summary>The key name for display: the WPF name, or "VKxx" for keys without one.</summary>
    public static string GetDisplayName(int virtualKey) =>
        GetName(virtualKey) ?? string.Create(System.Globalization.CultureInfo.InvariantCulture, $"VK{virtualKey:X2}");

    /// <summary>Built on first use, after the tables below are initialized.</summary>
    private static class Maps
    {
        public static readonly Dictionary<string, int> ByName = BuildByName();
        public static readonly Dictionary<int, string> ByCode = BuildByCode();
    }

    private static Dictionary<string, int> BuildByName()
    {
        var map = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
        foreach (var (name, vk) in Names)
        {
            map.TryAdd(name, vk);
        }

        return map;
    }

    private static Dictionary<int, string> BuildByCode()
    {
        var map = new Dictionary<int, string>();
        foreach (var (vk, name) in CanonicalNames)
        {
            map.TryAdd(vk, name);
        }

        return map;
    }

